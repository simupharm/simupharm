def save_csv(filename, data, fieldnames):
    p1 = os.path.join(dir1, filename)
    p2 = os.path.join(dir2, filename)
    for p in [p1, p2]:
        with open(p, 'w', newline='', encoding='utf-8') as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction='ignore', quoting=csv.QUOTE_ALL)
            writer.writeheader()
            for row in data:
                cleaned_row = {k: row.get(k, "N/A") for k in fieldnames}
                writer.writerow(cleaned_row)
    print(f"Saved {filename} to both directories ({len(data)} rows).")

